'use strict';

const fs = require('fs');
const path = require('path');
const { runScript } = require('./pm');

// ─── HELPERS ─────────────────────────────────────────────────────────────────

function dbLabel(db) {
    return {
        mongoose: 'Mongoose (MongoDB)',
        prisma: 'Prisma (PostgreSQL)',
        drizzle: 'Drizzle (PostgreSQL)',
    }[db] || db;
}

function modelPattern(db) {
    switch (db) {
        case 'mongoose':
            return 'Mongoose schemas — `new Schema<IModel>({...})` exported as `model<IModel>(\'Name\', schema)`';
        case 'prisma':
            return 'Prisma schema — models defined in `prisma/schema.prisma`, accessed via singleton `prisma` client in `src/app/utils/prisma.ts`';
        case 'drizzle':
            return 'Drizzle schemas — tables defined with `pgTable()` in model files, accessed via `drizzle(pool)` in `src/app/utils/drizzle.ts`';
        default:
            return '';
    }
}

function modelExample(db, moduleName) {
    const lower = moduleName.toLowerCase();

    switch (db) {
        case 'mongoose':
            return `\`\`\`ts
// src/app/modules/${moduleName}/${lower}.model.ts
import { Schema, model } from 'mongoose';
import { I${moduleName} } from './${lower}.interface';

const ${lower}Schema = new Schema<I${moduleName}>(
  {
    name: { type: String, required: true },
    // ... fields
  },
  { timestamps: true },
);

export const ${moduleName} = model<I${moduleName}>('${moduleName}', ${lower}Schema);
\`\`\``;

        case 'prisma':
            return `\`\`\`prisma
// prisma/schema.prisma
model ${moduleName} {
  id        String   @id @default(cuid())
  name      String
  createdAt DateTime @default(now())
  updatedAt DateTime @updatedAt
}
\`\`\`

Then access via:
\`\`\`ts
import { prisma } from '../../utils/prisma';
const items = await prisma.${lower}.findMany();
\`\`\``;

        case 'drizzle':
            return `\`\`\`ts
// src/app/modules/${moduleName}/${lower}.model.ts
import { pgTable, text, timestamp, varchar } from 'drizzle-orm/pg-core';
import crypto from 'crypto';

export const ${lower}s = pgTable('${lower}s', {
  id:        text('id').primaryKey().$defaultFn(() => crypto.randomUUID()),
  name:      varchar('name', { length: 255 }).notNull(),
  createdAt: timestamp('created_at').defaultNow(),
  updatedAt: timestamp('updated_at').defaultNow(),
});
\`\`\``;
        default:
            return '';
    }
}

function validationExample(validator, moduleName) {
    const lower = moduleName.toLowerCase();

    if (validator === 'zod') {
        return `\`\`\`ts
// src/app/modules/${moduleName}/${lower}.validation.ts
import { z } from 'zod';

const create${moduleName}Schema = z.object({
  body: z.object({
    name: z.string().min(1, 'Name is required'),
  }),
});

export const ${moduleName}Validation = { create${moduleName}Schema };
\`\`\``;
    }

    return `\`\`\`ts
// src/app/modules/${moduleName}/${lower}.validation.ts
import Joi from 'joi';

const create${moduleName}Schema = Joi.object({
  name: Joi.string().required().min(1),
});

export const ${moduleName}Validation = { create${moduleName}Schema };
\`\`\``;
}

function migrationCmd(db, pm) {
    switch (db) {
        case 'mongoose':
            return null; // Mongoose auto-syncs
        case 'prisma':
            return `${pm === 'npm' ? 'npx' : pm === 'yarn' ? 'yarn' : 'pnpm exec'} prisma migrate dev --name <migration_name>`;
        case 'drizzle':
            return `${pm === 'npm' ? 'npx' : pm === 'yarn' ? 'yarn' : 'pnpm exec'} drizzle-kit migrate`;
        default:
            return null;
    }
}

// ─── AGENTS.MD ───────────────────────────────────────────────────────────────

function buildAgentsMd(opts) {
    const {
        projectName, db, validator, useAuth, useDocker, tokenDelivery, pm = 'npm',
    } = opts;

    const lines = [];

    lines.push(`# AGENTS.md`);
    lines.push('');
    lines.push(`> Auto-generated by [create-express-modular](https://create-express-modular.lovable.app/). This file helps AI coding assistants understand the project.`);
    lines.push('');

    // ── Identity ─────────────────────────────────────────────────────────────
    lines.push(`## Project: ${projectName}`);
    lines.push('');
    lines.push(`A production-ready, domain-driven **Express + TypeScript** backend.`);
    lines.push('');

    // ── Stack ────────────────────────────────────────────────────────────────
    lines.push('## Tech Stack');
    lines.push('');
    lines.push(`- **Runtime**: Node.js ≥ 18`);
    lines.push(`- **Framework**: Express`);
    lines.push(`- **Language**: TypeScript (strict)`);
    lines.push(`- **Database / ORM**: ${dbLabel(db)}`);
    lines.push(`- **Validation**: ${validator === 'zod' ? 'Zod' : 'Joi'}`);
    lines.push(`- **Package Manager**: ${pm}`);
    if (useAuth) {
        const delivery = tokenDelivery === 'cookie' ? 'HTTP-only cookies' : 'Authorization header';
        lines.push(`- **Auth**: JWT with bcrypt + rate limiting (${delivery})`);
    }
    if (useDocker) {
        lines.push(`- **Docker**: Dockerfile + docker-compose`);
    }
    lines.push('');

    // ── Architecture Rules ──────────────────────────────────────────────────
    lines.push('## Architecture Rules');
    lines.push('');
    lines.push('1. All source code lives under `src/`.');
    lines.push('2. **Modules** follow domain-driven design: `src/app/modules/<Name>/` with files named `<name>.controller.ts`, `<name>.service.ts`, `<name>.route.ts`, `<name>.model.ts`, `<name>.interface.ts`, `<name>.validation.ts`.');
    lines.push('3. **Middleware** files MUST be named `<name>.middleware.ts` inside `src/app/middlewares/`. The build will fail otherwise.');
    lines.push('4. Routes are auto-registered in `src/app/routes/index.ts` via inject markers (`// --- INJECT IMPORTS HERE ---` and `// --- INJECT ROUTES HERE ---`). Do NOT remove these markers.');
    lines.push('5. **All environment variables** go through `src/app/config/index.ts` — never use `process.env` directly in application code.');
    lines.push('6. Wrap all async route handlers with `catchAsync()` from `src/app/utils/catchAsync.ts`.');
    lines.push('7. Use `sendResponse()` from `src/app/utils/sendResponse.ts` for all API responses.');
    lines.push('8. Use `validateRequest()` middleware to validate incoming request bodies against schemas.');

    if (db === 'mongoose') {
        lines.push('9. Use `QueryBuilder` from `src/app/utils/QueryBuilder.ts` for search, filter, sort, and pagination on Mongoose queries.');
    }

    lines.push('');

    // ── Model Pattern ───────────────────────────────────────────────────────
    lines.push('## Model Pattern');
    lines.push('');
    lines.push(modelPattern(db));
    lines.push('');

    // ── CLI Commands ────────────────────────────────────────────────────────
    lines.push('## CLI Commands');
    lines.push('');
    lines.push('Use the CEM CLI for scaffolding — do NOT create module/middleware files manually.');
    lines.push('');
    lines.push('| Command | Effect |');
    lines.push('|---|---|');
    lines.push('| `cem add module <Name...>` | Scaffold module(s) with all files + auto-wire routes |');
    lines.push('| `cem add middleware <name...>` | Create middleware file(s) with correct naming |');
    lines.push('| `cem add env <KEY...>` | Add env var(s) to `.env`, `.env.example`, and `config/index.ts` |');
    lines.push('| `cem remove module <Name>` | Delete module + unwire route |');
    lines.push('| `cem remove middleware <name>` | Delete middleware file |');
    lines.push('| `cem remove env <KEY>` | Remove env var from all config files |');
    lines.push('| `cem dev` | Start dev server with hot reload |');
    lines.push('| `cem build` | Convention guards + TypeScript compilation |');
    lines.push('| `cem check` | Type-check + lint + format check |');
    lines.push('');

    const migrate = migrationCmd(db, pm);
    if (migrate) {
        lines.push('## Database Migrations');
        lines.push('');
        lines.push('```bash');
        lines.push(migrate);
        lines.push('```');
        lines.push('');
    }

    // ── Don'ts ──────────────────────────────────────────────────────────────
    lines.push('## Do NOT');
    lines.push('');
    lines.push('- Create module files manually — use `cem add module`.');
    lines.push('- Use `process.env` directly — import `config` from `src/app/config`.');
    lines.push('- Rename middleware files without the `.middleware.ts` suffix — `cem build` will reject it.');
    lines.push('- Remove the inject markers in `src/app/routes/index.ts`.');
    lines.push('- Modify core middlewares (`globalErrorHandler`, `notFound`' + (useAuth ? ', `auth`, `rateLimiter`' : '') + ') unless intentional.');
    lines.push('');

    return lines.join('\n');
}

