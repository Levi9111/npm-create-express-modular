// ─── PUBLIC API ──────────────────────────────────────────────────────────────

/**
 * Generate AGENTS.md and CLAUDE.md tailored to the scaffolded project.
 *
 * @param {string} projectPath  Absolute path to the new project directory
 * @param {object} opts
 * @param {string} opts.projectName
 * @param {string} opts.db           'mongoose' | 'prisma' | 'drizzle'
 * @param {string} opts.validator    'zod' | 'joi'
 * @param {boolean} opts.useAuth
 * @param {boolean} opts.useDocker
 * @param {string} opts.tokenDelivery 'cookie' | 'header'
 * @param {string} opts.pm           'npm' | 'yarn' | 'pnpm'
 */
function generateAgentDocs(projectPath, opts) {
    fs.writeFileSync(path.join(projectPath, 'AGENTS.md'), buildAgentsMd(opts));
    fs.writeFileSync(path.join(projectPath, 'CLAUDE.md'), buildClaudeMd(opts));
}

module.exports = { generateAgentDocs };
